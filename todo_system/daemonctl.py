"""Cross-platform control of the MaestroACP background daemons.

macOS runs them as launchd LaunchAgents (labels ``<prefix>*``); the cloud HQ
(Ubuntu, since 2026-09-11 — ``Decisions/2026-09-11-macp-cloud-hq-provider.md``)
runs the same jobs as ``systemd --user`` units generated by
``scripts/systemd/gen_units.py``. Everything that used to shell out to
``launchctl`` goes through here so both hosts share one code path and the
label stays the stable identifier in logs, state files and notifications.

Stdlib-only: this is imported by the maintenance tick and by bare-python3
scripts (health_report, claude_auth_watch, claude_upgrade).
"""

from __future__ import annotations

import os
import subprocess
import sys

from todo_system.paths import label_prefix

IS_DARWIN = sys.platform == "darwin"

# Org segment shared by every daemon label (neutral default "com.macp."), resolved
# once at import from MACP_LABEL_PREFIX / .macp config / the default; an installed
# vault pins its real prefix in .macp/config.toml. SECONDBRAIN_PREFIX is the product
# sub-namespace inside it; the health sweep filters on it (loaded_pids / session_end),
# so org-level install-only units like kis-trading-real stay outside it. Downstream
# modules (session_end, worker) read these two names instead of re-hard-coding the
# "<prefix>secondbrain." literal.
LABEL_PREFIX = label_prefix()
SECONDBRAIN_PREFIX = f"{LABEL_PREFIX}secondbrain."


def build_units(prefix: str) -> dict[str, str]:
    """launchd label -> systemd --user unit stem (without ``.service``) for every
    daemon, with labels assembled from ``prefix`` — the org segment, e.g.
    ``"com.macp."`` including its trailing dot. The unit stems double as the
    log-file stems under logs/ on Linux and do not change with the prefix.

    ``secondbrain.`` stays a fixed product sub-namespace *inside* the prefix so the
    two-tier layout survives a custom prefix: the health sweep filters on
    ``f"{prefix}secondbrain."`` and must keep excluding org-level install-only
    units such as ``kis-trading-real``. ``build_units(<installed prefix>)`` is
    byte-identical to the dict that host's daemons shipped with (guarded in
    test_daemonctl, which pins the concrete shipped labels).
    """
    sb = f"{prefix}secondbrain."
    return {
        f"{sb}runner.worker-default": "macp-runner-worker-default",
        f"{sb}orchestrator": "macp-orchestrator",
        f"{sb}planner": "macp-planner",
        f"{sb}maintenance": "macp-maintenance",
        f"{sb}macp-monitor": "macp-monitor",
        f"{sb}todo-sync": "macp-todo-sync",
        f"{sb}dashboard": "macp-dashboard",
        f"{sb}brief": "macp-brief",
        f"{sb}kakao-refresh": "macp-kakao-refresh",
        f"{sb}health": "macp-health",
        f"{prefix}claude-auth-watch": "claude-auth-watch",
        f"{prefix}claude-upgrade": "claude-upgrade",
        f"{prefix}claude-remote-control": "claude-remote-control",
        f"{prefix}claude-remote-control-watchdog": "claude-remote-control-watchdog",
        f"{prefix}mailroom.tick": "mailroom-tick",
        f"{prefix}kis-trading": "kis-trading",
        f"{prefix}kis-trading-livesync": "kis-trading-livesync",
        f"{prefix}kis-trading-watchdog": "kis-trading-watchdog",
        # Real-account loop: install-only unit (scripts/systemd/gen_units.py never
        # enables it), but the label still needs a stable identity for restart/status
        # hints and log stems once a human arms it by hand.
        f"{prefix}kis-trading-real": "kis-trading-real",
    }


# launchd label -> systemd --user unit name (without ``.service``). The unit
# names double as the log-file stems under logs/ on Linux.
UNITS: dict[str, str] = build_units(LABEL_PREFIX)
LABELS: dict[str, str] = {unit: label for label, unit in UNITS.items()}


def unit_name(label: str) -> str:
    """systemd unit stem for a launchd label (identity for unknown labels)."""
    return UNITS.get(label, label)


def label_for(unit: str) -> str:
    """launchd label for a systemd unit stem (identity for unknown units)."""
    return LABELS.get(unit, unit)


def _run(cmd: list[str], timeout: int) -> subprocess.CompletedProcess[str]:
    return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)


def restart(label: str, timeout: int = 120) -> subprocess.CompletedProcess[str]:
    """Kill-and-relaunch the daemon behind ``label`` (``launchctl kickstart -k``
    / ``systemctl --user restart``). Returns the CompletedProcess so callers keep
    their existing returncode/stderr handling."""
    if IS_DARWIN:
        return _run(["launchctl", "kickstart", "-k", f"gui/{os.getuid()}/{label}"], timeout)
    return _run(["systemctl", "--user", "restart", f"{unit_name(label)}.service"], timeout)


def restart_hint(label: str) -> str:
    """The command a human would type to do what ``restart`` does — for messages."""
    if IS_DARWIN:
        return f"launchctl kickstart -k gui/$(id -u)/{label}"
    return f"systemctl --user restart {unit_name(label)}.service"


def status_hint(label: str) -> str:
    if IS_DARWIN:
        return f"launchctl print gui/$(id -u)/{label}"
    return f"systemctl --user status {unit_name(label)}.service"


def main_pid(label: str) -> int | None:
    """Live PID of the daemon behind ``label``; None when loaded-but-idle
    (interval jobs between ticks), not loaded, or unqueryable."""
    if IS_DARWIN:
        pids = loaded_pids(prefix="")
        return None if pids is None else pids.get(label)
    try:
        out = _run(["systemctl", "--user", "show", "-p", "LoadState", "-p", "MainPID",
                    f"{unit_name(label)}.service"], 30).stdout
    except (OSError, subprocess.SubprocessError):
        return None
    fields = dict(line.split("=", 1) for line in out.splitlines() if "=" in line)
    if fields.get("LoadState") != "loaded":
        return None
    try:
        pid = int(fields.get("MainPID", "0"))
    except ValueError:
        return None
    return pid or None


def loaded_pids(prefix: str | None = None) -> dict[str, int | None] | None:
    """label -> PID (None = loaded but not running) for every known daemon whose
    label starts with ``prefix``. None when the platform's controller is absent.

    ``prefix`` defaults (when None) to ``f"{label_prefix()}secondbrain."`` resolved
    at *call* time, so a ``MACP_LABEL_PREFIX`` set after import is honoured; with it
    unset this uses the neutral default prefix (an installed vault's config key
    restores its real prefix). Pass an explicit
    ``prefix=""`` to sweep every loaded label (``main_pid`` does)."""
    if prefix is None:
        prefix = f"{label_prefix()}secondbrain."
    if IS_DARWIN:
        try:
            out = _run(["launchctl", "list"], 30).stdout
        except (OSError, subprocess.SubprocessError):
            return None
        pids: dict[str, int | None] = {}
        for line in out.splitlines():
            cols = line.split("\t") if "\t" in line else line.split()
            if len(cols) < 3:
                continue
            label = cols[-1].strip()
            if not label.startswith(prefix):
                continue
            try:
                pids[label] = int(cols[0].strip())
            except ValueError:
                pids[label] = None
        return pids
    pids = {}
    for label in UNITS:
        if not label.startswith(prefix):
            continue
        try:
            out = _run(["systemctl", "--user", "show", "-p", "LoadState", "-p", "MainPID",
                        f"{unit_name(label)}.service"], 30).stdout
        except FileNotFoundError:
            return None
        except (OSError, subprocess.SubprocessError):
            continue
        fields = dict(line.split("=", 1) for line in out.splitlines() if "=" in line)
        if fields.get("LoadState") != "loaded":
            continue
        try:
            pid = int(fields.get("MainPID", "0"))
        except ValueError:
            pid = 0
        pids[label] = pid or None
    return pids
